function launchPresentation({version, alias, peerKey, wallet, poolId, feeBasisPoints, threads, nodeChain, nodeHeight, topic}) {
  const feePct = (Number(feeBasisPoints || 0) / 100).toFixed(2)
  return `${BYZE_P2POOL_BANNER}\n\nCLI ${version}   ${alias}\n\nPeer       ${peerKey} (temporary)\nWallet     ${wallet}\nPool       ${poolId} | fee ${feePct}%\nCPU        ${threads} thread(s) RandomX\nNode       ${nodeChain || '?'} | height ${nodeHeight || 0}\nTopic      ${topic}\n───────────────────────────────────────────────────────────────────────`
}

function statusLine({time, localHashrate, minerCount, poolHashrate, localShares, remoteAccepted=0, remotePending=0, remoteRejected=0, droppedStale=0, forkCount=0, reorgCount=0, sessionByze, lastRejectCode=''}) {
  const remote = ` | Remote A/P/R ${Number(remoteAccepted||0)}/${Number(remotePending||0)}/${Number(remoteRejected||0)}`
  const stale = Number(droppedStale || 0) > 0 ? ` | Stale ${Number(droppedStale)}` : ''
  const forks = Number(forkCount || 0) > 0 || Number(reorgCount || 0) > 0 ? ` | Forks ${Number(forkCount||0)} · Reorgs ${Number(reorgCount||0)}` : ''
  const last = lastRejectCode ? ` | Last ${String(lastRejectCode).slice(0,48)}` : ''
  return `${time} | RandomX ${localHashrate} | Pool ${minerCount} miner(s) · ${poolHashrate} | Shares ${localShares}${remote}${stale}${forks} | Session +${sessionByze || '0'} BYZE${last}`
}

function rewardCelebration({amountByze, height, sessionByze, alias}) {
  const width = 112
  const rule = '═'.repeat(width)
  const center = (s) => {
    const raw = String(s)
    const pad = Math.max(0, width - 2 - raw.length)
    const left = Math.floor(pad / 2)
    return `║${' '.repeat(left)}${raw}${' '.repeat(pad-left)}║`
  }
  return `${MINING_SUCCESS_BANNER}\n${rule}\n${center(`⛏  ${alias}  ⛏`)}\n${center(`+${amountByze} BYZE`)}\n${center(`BYZE block #${height}`)}\n${center(`Session earnings: ${sessionByze} BYZE`)}\n${rule}`
}

